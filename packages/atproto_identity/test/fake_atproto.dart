import 'dart:async';
import 'dart:convert';
import 'dart:io';

import 'package:atproto_identity/atproto_identity.dart'
    show IdentityException; // not re-exported by atproto_oauth
import 'package:atproto_oauth/atproto_oauth.dart';
import 'package:http/http.dart' as http;
import 'package:http/io_client.dart';

import 'package:rooms_atproto/rooms_atproto.dart';

/// A minimal in-test AT Protocol world: one origin acting as PDS *and*
/// authorization server, over **real TLS** (the `atproto_oauth` client
/// hardcodes https for AS metadata/PAR/token, so the fake must speak it).
/// The certificate is self-signed and generated per run; [httpClient]
/// trusts it. Identity resolution is injected instead of served.
///
/// Real-world differences (kept honest, not implemented here):
/// - No account chooser / consent screen on `/oauth/authorize` — the
///   "user" always approves.
/// - No DPoP proof verification, no token/refresh rotation bookkeeping
///   beyond what the flow needs, no PKCE verification (PAR params are
///   recorded for tests to assert on).
/// - The certificate is generated by openssl at test time; production
///   authorization servers present real chains.
class FakeAtprotoServer {
  FakeAtprotoServer({this.expiresInSeconds = 3600});

  /// Access-token lifetime in the token response; mutable so a test can
  /// issue a stale session and then re-issue a fresh one.
  int expiresInSeconds;
  final _identities = <String, String>{}; // handle -> did
  final _parRequests = <String, Map<String, String>>{}; // request_uri -> form
  final _codes = <String, String>{}; // code -> did
  final _refreshTokens = <String, String>{}; // refresh -> did
  final parCalls = <Map<String, String>>[];
  final tokenCalls = <Map<String, String>>[];
  HttpServer? _server;
  Directory? _certDir;
  http.Client? _client;

  String get origin => 'https://127.0.0.1:${_server!.port}';
  bool get running => _server != null;

  /// A fresh client that trusts this server's self-signed certificate
  /// (the manager closes the clients it is handed).
  http.Client newClient() => IOClient(
        HttpClient()
          ..badCertificateCallback =
              (X509Certificate cert, String host, int port) =>
                  host == '127.0.0.1',
      );

  /// A shared client that trusts this server's self-signed certificate.
  http.Client get httpClient => _client ??= newClient();

  void addIdentity(String handle, String did) => _identities[handle] = did;

  IdentityResolver resolver() => _FakeResolver(this);

  Future<void> start() async {
    final certDir = _certDir = await Directory.systemTemp.createTemp('fake-atproto-');
    final cert = '${certDir.path}/cert.pem';
    final key = '${certDir.path}/key.pem';
    final generated = await Process.run('openssl', [
      'req', '-x509', '-newkey', 'ec', '-pkeyopt', 'ec_paramgen_curve:prime256v1',
      '-keyout', key, '-out', cert, '-days', '2', '-nodes',
      '-subj', '/CN=127.0.0.1', '-addext', 'subjectAltName=IP:127.0.0.1',
    ]);
    if (generated.exitCode != 0) {
      throw StateError('openssl failed: ${generated.stderr}');
    }
    final context = SecurityContext()
      ..useCertificateChain(cert)
      ..usePrivateKey(key);
    final server = _server = await HttpServer.bindSecure(
      '127.0.0.1',
      0,
      context,
    );
    server.listen((request) => unawaited(_handle(request)));
  }

  Future<void> stop() async {
    await _server?.close(force: true);
    _server = null;
    _client?.close();
    _client = null;
    try {
      await _certDir?.delete(recursive: true);
    } catch (_) {}
    _certDir = null;
  }

  Future<void> _handle(HttpRequest request) async {
    try {
      final path = request.uri.path;
      if (path == '/.well-known/oauth-protected-resource' &&
          request.method == 'GET') {
        await _json(request, 200, {
          'authorization_servers': [origin],
        });
        return;
      }
      if (path == '/.well-known/oauth-authorization-server' &&
          request.method == 'GET') {
        await _json(request, 200, {
          'issuer': origin,
          'authorization_endpoint': '$origin/oauth/authorize',
          'pushed_authorization_request_endpoint': '$origin/oauth/par',
          'token_endpoint': '$origin/oauth/token',
        });
        return;
      }
      if (path == '/oauth/par' && request.method == 'POST') {
        final form = await _form(request);
        parCalls.add(form);
        final uri = 'par_${parCalls.length}';
        _parRequests[uri] = form;
        await _json(request, 201, {'request_uri': uri, 'expires_in': 300});
        return;
      }
      if (path == '/oauth/authorize' && request.method == 'GET') {
        final par = _parRequests[request.uri.queryParameters['request_uri']];
        if (par == null) {
          await _json(request, 400, {'error': 'invalid_request_uri'});
          return;
        }
        final did = _identities[par['login_hint']] ??
            _identities.values.first;
        final code = 'code_${_codes.length + 1}';
        _codes[code] = did;
        final redirect = Uri.parse(par['redirect_uri']!).replace(
          queryParameters: {
            'code': code,
            'state': par['state']!,
            'iss': origin,
          },
        );
        // The "browser": approve and bounce back to the client.
        request.response.statusCode = 302;
        request.response.headers.set(HttpHeaders.locationHeader, '$redirect');
        await request.response.close();
        return;
      }
      if (path == '/oauth/token' && request.method == 'POST') {
        final form = await _form(request);
        tokenCalls.add(form);
        final grant = form['grant_type'];
        String? did;
        if (grant == 'authorization_code') did = _codes[form['code']];
        if (grant == 'refresh_token') {
          did = _refreshTokens[form['refresh_token']];
        }
        if (did == null) {
          await _json(request, 400, {'error': 'invalid_grant'});
          return;
        }
        final refresh = 'rt_${tokenCalls.length}';
        _refreshTokens[refresh] = did;
        await _json(request, 200, {
          'access_token': 'at_${tokenCalls.length}',
          'token_type': 'DPoP',
          'scope': 'atproto',
          'sub': did,
          'expires_in': expiresInSeconds,
          'refresh_token': refresh,
        });
        return;
      }
      await _json(request, 404, {'error': 'not_found'});
    } catch (_) {
      try {
        await request.response.close();
      } catch (_) {}
    }
  }

  Future<Map<String, String>> _form(HttpRequest request) async {
    final body = await utf8.decoder.bind(request).join();
    return Uri.splitQueryString(body);
  }

  Future<void> _json(
    HttpRequest request,
    int status,
    Map<String, dynamic> body,
  ) async {
    request.response.statusCode = status;
    request.response.headers.contentType = ContentType.json;
    request.response.write(jsonEncode(body));
    await request.response.close();
  }
}

final class _FakeResolver implements IdentityResolver {
  _FakeResolver(this.server);
  final FakeAtprotoServer server;

  @override
  Future<ResolvedIdentity> resolve(String value) async {
    final did = server._identities[value];
    if (did == null) throw IdentityException('Unknown handle: $value');
    return ResolvedIdentity(did: did, pds: server.origin, handle: value);
  }
}

/// Simulates the user's browser: follows the authorization URL (including
/// the redirect back to the client's loopback listener), trusting the
/// fake's self-signed certificate.
Future<bool> browserVisit(FakeAtprotoServer server, Uri url) async {
  try {
    final response = await server.httpClient.get(url);
    return response.statusCode == 200;
  } catch (_) {
    return false;
  }
}

/// In-memory [AccountVault] for tests.
final class MemoryVault implements AccountVault {
  String? value;
  @override
  Future<String?> read() async => value;
  @override
  Future<void> write(String newValue) async => value = newValue;
  @override
  Future<void> delete() async => value = null;
}
